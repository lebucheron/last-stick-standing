import assert from 'node:assert/strict';
import '../cosmetics-core.js';
import {MatchRoom} from '../backend/worker.js';
const C=globalThis.LastStickCosmeticsCore,p=C.clean();
assert.equal(C.items.length,26);
assert.equal(p.owned.length,8);
assert.equal(C.state(C.find('forest-moss'),p),'locked');
for(let i=0;i<15;i++)assert.equal(C.complete(p,'round-'+i,i<3),true);
assert.equal(C.complete(p,'round-0',true),false);
assert.equal(C.state(C.find('forest-moss'),p),'unlocked');
assert.equal(C.state(C.find('rave-pulse'),p),'locked');
p.games=25;assert.equal(C.state(C.find('rave-pulse'),p),'unlocked');
p.games=50;p.wins=7;assert.equal(C.state(C.find('golden-stick'),p),'unlocked');
p.owned.push('golden-stick');assert.equal(C.state(C.find('golden-stick'),p),'owned');
p.equipped.skins='golden-stick';assert.equal(C.state(C.find('golden-stick'),p),'equipped');
assert.deepEqual(C.publicLoadout(p),{skin:'golden-stick',death:'pouf'});
assert.deepEqual(C.validatePublic({skin:'golden-stick',death:'duck-escape',arena:'golden-temple'}),{skin:null,death:'pouf'});
assert.equal(C.tokenUnits(25,500000,6),'500000');
assert.equal(C.tokenUnits(25,250000,6),'1000000');
assert.throws(()=>C.tokenUnits(25,0,6));
assert.equal(C.clean({equipped:{skins:'golden-stick'}}).equipped.skins,null);
const messages=[],round={id:'test-round',raceAt:Date.now()+9000,bets:{'player-one':['A'],'other-player':['A']},bots:[]},data=new Map([['round',round]]);
const socket={deserializeAttachment:()=>({player:'player-one'}),send:m=>messages.push(JSON.parse(m))};
const room=new MatchRoom({getWebSockets:()=>[socket],storage:{get:async key=>data.get(key),put:async(key,value)=>data.set(key,value)}},{});
await room.webSocketMessage(socket,JSON.stringify({type:'cosmetic_selection',roundId:round.id,runner:'A',skin:'classic-blue',death:'duck-escape',arena:'golden-temple'}));
assert.deepEqual(round.cosmetics.A,{skin:'classic-blue',death:'pouf'});
assert.equal(messages.at(-1).type,'cosmetics');
const other={deserializeAttachment:()=>({player:'other-player'})};
await room.webSocketMessage(other,JSON.stringify({type:'cosmetic_selection',roundId:round.id,runner:'A',skin:'classic-green'}));
assert.equal(round.cosmetics.A.skin,'classic-blue');
data.set('cosmetic-owned:player-one',['golden-stick']);
await room.webSocketMessage(socket,JSON.stringify({type:'cosmetic_selection',roundId:round.id,runner:'A',skin:'golden-stick',death:'pouf'}));
assert.equal(round.cosmetics.A.skin,'golden-stick');
console.log('Cosmetics: catalogue, progression, states, conversion and multiplayer validation passed');
